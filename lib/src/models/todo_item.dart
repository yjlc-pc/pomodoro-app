import 'package:flutter/foundation.dart';

/// How urgent a todo is.
///
/// Deliberately three levels rather than a number: the UI shows the level as
/// both a left colour bar and a text label, and a number would invite fiddling
/// that has no meaning here.
enum TodoPriority {
  low('低'),
  normal('普通'),
  high('高');

  const TodoPriority(this.label);

  /// User-facing label.
  final String label;

  static TodoPriority fromName(String? name) => TodoPriority.values.firstWhere(
        (p) => p.name == name,
        orElse: () => TodoPriority.normal,
      );
}

/// One step within a todo. Titled and completable, nothing more — a step that
/// needed its own description would be its own todo.
@immutable
class SubTask {
  const SubTask({
    required this.id,
    required this.title,
    this.done = false,
  });

  final String id;
  final String title;
  final bool done;

  SubTask copyWith({String? title, bool? done}) => SubTask(
        id: id,
        title: title ?? this.title,
        done: done ?? this.done,
      );

  Map<String, Object?> toJson() => {'id': id, 'title': title, 'done': done};

  factory SubTask.fromJson(Map<String, Object?> json) => SubTask(
        id: json['id'] as String,
        title: json['title'] as String,
        done: json['done'] as bool? ?? false,
      );
}

/// A single todo entry: title, priority, description and optional sub-steps.
@immutable
class TodoItem {
  const TodoItem({
    required this.id,
    required this.title,
    required this.createdAt,
    this.done = false,
    this.priority = TodoPriority.normal,
    this.description = '',
    this.subtasks = const <SubTask>[],
  });

  /// Unique id (timestamp + counter based, generated by [TodoStore]).
  final String id;

  /// The task text. Non-empty by construction (see [TodoStore.add]).
  final String title;

  final bool done;

  final TodoPriority priority;

  /// Free-form notes, edited inline in the detail sheet. May be empty.
  final String description;

  /// The steps this todo breaks into, in display order.
  final List<SubTask> subtasks;

  final DateTime createdAt;

  /// How many sub-steps are done, and how many there are.
  int get doneSubtaskCount => subtasks.where((s) => s.done).length;

  bool get hasSubtasks => subtasks.isNotEmpty;

  /// True when every sub-step is done. Meaningless with no sub-steps, which is
  /// why callers must check [hasSubtasks] first.
  bool get subtasksComplete => hasSubtasks && doneSubtaskCount == subtasks.length;

  TodoItem copyWith({
    String? title,
    bool? done,
    TodoPriority? priority,
    String? description,
    List<SubTask>? subtasks,
  }) {
    return TodoItem(
      id: id,
      title: title ?? this.title,
      done: done ?? this.done,
      priority: priority ?? this.priority,
      description: description ?? this.description,
      subtasks: subtasks ?? this.subtasks,
      createdAt: createdAt,
    );
  }

  Map<String, Object?> toJson() => {
        'id': id,
        'title': title,
        'done': done,
        'priority': priority.name,
        'description': description,
        'subtasks': [for (final s in subtasks) s.toJson()],
        'createdAt': createdAt.toIso8601String(),
      };

  /// Tolerates entries written before the priority / description / subtask
  /// fields existed, so an older stored blob still loads instead of throwing.
  factory TodoItem.fromJson(Map<String, Object?> json) {
    final rawSubtasks = json['subtasks'];
    return TodoItem(
      id: json['id'] as String,
      title: json['title'] as String,
      done: json['done'] as bool,
      priority: TodoPriority.fromName(json['priority'] as String?),
      description: json['description'] as String? ?? '',
      subtasks: rawSubtasks is List
          ? [
              for (final entry in rawSubtasks)
                SubTask.fromJson(
                  (entry as Map).cast<String, Object?>(),
                ),
            ]
          : const <SubTask>[],
      createdAt: DateTime.parse(json['createdAt'] as String),
    );
  }
}